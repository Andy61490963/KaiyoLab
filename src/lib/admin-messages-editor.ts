// 僅翻譯已知的後端警告模板，網址、錨點與原始語法診斷保留原文
export function editorMessage(key: string, language: 'zh-TW' | 'en'): string | undefined {
  if (Object.hasOwn(editorMessages, key)) return language === 'zh-TW' ? editorMessages[key] : key;
  if (Object.hasOwn(reviewMessages, key)) return language === 'en' ? reviewMessages[key] : key;
  let match: RegExpMatchArray | null;
  if ((match = key.match(/^(\d+) body images? (?:has|have) no alternative text$/)))
    return language === 'zh-TW' ? `${match[1]} 張內文圖片尚未填寫替代文字` : key;
  if ((match = key.match(/^No published content at (.+)$/)))
    return language === 'zh-TW' ? `找不到此網址的公開內容：${match[1]}` : key;
  if ((match = key.match(/^(\d+) more unpublished or missing content links$/)))
    return language === 'zh-TW' ? `另外有 ${match[1]} 個尚未發布或不存在的內容連結` : key;
  if ((match = key.match(/^找不到章節錨點：(.+)$/)))
    return language === 'en' ? `Section anchor not found: ${match[1]}` : key;
  if ((match = key.match(/^另外有 (\d+) 個找不到的章節錨點$/)))
    return language === 'en' ? `${match[1]} more section anchors could not be found` : key;
  if ((match = key.match(/^本次檢查前 (\d+) 張 Mermaid 圖表，其餘 (\d+) 張請分批檢查$/)))
    return language === 'en'
      ? `Checked the first ${match[1]} Mermaid diagrams. Check the remaining ${match[2]} in smaller batches`
      : key;
  if ((match = key.match(/^第 (\d+) 行的 Mermaid 圖表不符合支援範圍：(.+)$/))) {
    const detail = editorMessage(match[2], language) ?? match[2];
    return language === 'en'
      ? `Unsupported Mermaid diagram at line ${match[1]}: ${detail}`
      : `第 ${match[1]} 行的 Mermaid 圖表不符合支援範圍：${detail}`;
  }
  if ((match = key.match(/^第 (\d+) 行的 Mermaid 圖表語法錯誤：([\s\S]+)$/))) {
    const detail =
      Object.hasOwn(reviewMessages, match[2]) && language === 'en'
        ? reviewMessages[match[2]]
        : match[2];
    return language === 'en' ? `Mermaid syntax error at line ${match[1]}: ${detail}` : key;
  }
  return undefined;
}
